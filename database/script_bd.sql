BEGIN;

-- ---------------------------------------------------------------------
-- 1. USUARIOS (tabla estándar de Django)
-- ---------------------------------------------------------------------
CREATE TABLE auth_user (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    password      VARCHAR(128) NOT NULL,
    last_login    TIMESTAMPTZ,
    is_superuser  BOOLEAN      NOT NULL DEFAULT FALSE,
    username      VARCHAR(150) NOT NULL UNIQUE,
    first_name    VARCHAR(150) NOT NULL DEFAULT '',
    last_name     VARCHAR(150) NOT NULL DEFAULT '',
    email         VARCHAR(254) NOT NULL DEFAULT '',
    is_staff      BOOLEAN      NOT NULL DEFAULT FALSE,
    is_active     BOOLEAN      NOT NULL DEFAULT TRUE,
    date_joined   TIMESTAMPTZ  NOT NULL DEFAULT NOW()
);

-- ---------------------------------------------------------------------
-- 2. CUENTAS: perfiles (roles), clientes y notificaciones
-- ---------------------------------------------------------------------
CREATE TABLE cuentas_perfil (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id  BIGINT      NOT NULL UNIQUE
                REFERENCES auth_user (id) ON DELETE CASCADE,
    rol         VARCHAR(15) NOT NULL
                CHECK (rol IN ('ADMIN', 'RECEPCION', 'ENTRENADOR', 'FINANCIERO', 'CLIENTE'))
);

CREATE TABLE cuentas_cliente (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id       BIGINT       NOT NULL UNIQUE
                     REFERENCES auth_user (id) ON DELETE CASCADE,
    documento        VARCHAR(20)  NOT NULL UNIQUE,
    telefono         VARCHAR(20)  NOT NULL,
    direccion        VARCHAR(200) NOT NULL DEFAULT '',
    fecha_nacimiento DATE,
    activo           BOOLEAN      NOT NULL DEFAULT TRUE,
    fecha_registro   TIMESTAMPTZ  NOT NULL DEFAULT NOW()
);

CREATE TABLE cuentas_notificacion (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id   BIGINT      NOT NULL
                 REFERENCES cuentas_cliente (id) ON DELETE CASCADE,
    mensaje      TEXT        NOT NULL,
    leida        BOOLEAN     NOT NULL DEFAULT FALSE,
    fecha_envio  TIMESTAMPTZ NOT NULL DEFAULT NOW()
);


-- ---------------------------------------------------------------------
-- 3. MEMBRESÍAS: planes y membresías de los clientes
-- ---------------------------------------------------------------------
CREATE TABLE membresias_planmembresia (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre         VARCHAR(100)  NOT NULL UNIQUE,
    descripcion    TEXT          NOT NULL DEFAULT '',
    duracion_dias  INTEGER       NOT NULL CHECK (duracion_dias > 0),
    precio         NUMERIC(10,2) NOT NULL CHECK (precio >= 0),
    activo         BOOLEAN       NOT NULL DEFAULT TRUE
);

CREATE TABLE membresias_membresia (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id         BIGINT      NOT NULL
                       REFERENCES cuentas_cliente (id) ON DELETE RESTRICT,
    plan_id            BIGINT      NOT NULL
                       REFERENCES membresias_planmembresia (id) ON DELETE RESTRICT,
    fecha_inicio       DATE        NOT NULL DEFAULT CURRENT_DATE,
    fecha_vencimiento  DATE        NOT NULL,
    estado             VARCHAR(12) NOT NULL DEFAULT 'ACTIVA'
                       CHECK (estado IN ('ACTIVA', 'VENCIDA', 'CANCELADA')),
    motivo_cancelacion TEXT        NOT NULL DEFAULT '',
    creada_en          TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CHECK (fecha_vencimiento >= fecha_inicio)
);

-- ---------------------------------------------------------------------
-- 4. FACTURACIÓN: facturas y pagos
-- ---------------------------------------------------------------------
CREATE TABLE facturacion_factura (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero         VARCHAR(30)   NOT NULL UNIQUE,
    cliente_id     BIGINT        NOT NULL
                   REFERENCES cuentas_cliente (id) ON DELETE RESTRICT,
    membresia_id   BIGINT
                   REFERENCES membresias_membresia (id) ON DELETE RESTRICT,
    fecha_emision  DATE          NOT NULL DEFAULT CURRENT_DATE,
    subtotal       NUMERIC(10,2) NOT NULL CHECK (subtotal >= 0),
    impuesto       NUMERIC(10,2) NOT NULL DEFAULT 0 CHECK (impuesto >= 0),
    total          NUMERIC(10,2) NOT NULL CHECK (total >= 0),
    estado         VARCHAR(12)   NOT NULL DEFAULT 'PENDIENTE'
                   CHECK (estado IN ('PENDIENTE', 'PAGADA', 'ANULADA'))
);

CREATE TABLE facturacion_pago (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    factura_id  BIGINT        NOT NULL
                REFERENCES facturacion_factura (id) ON DELETE RESTRICT,
    fecha_pago  TIMESTAMPTZ   NOT NULL DEFAULT NOW(),
    monto       NUMERIC(10,2) NOT NULL CHECK (monto > 0),
    metodo      VARCHAR(20)   NOT NULL
                CHECK (metodo IN ('EFECTIVO', 'TARJETA', 'TRANSFERENCIA', 'YAPE_PLIN')),
    referencia  VARCHAR(100)  NOT NULL DEFAULT ''
);


-- ---------------------------------------------------------------------
-- 5. ENTRENAMIENTO: programas, ejercicios, sesiones y progreso
-- ---------------------------------------------------------------------
CREATE TABLE entrenamiento_programaentrenamiento (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id     BIGINT       NOT NULL
                   REFERENCES cuentas_cliente (id) ON DELETE RESTRICT,
    entrenador_id  BIGINT       NOT NULL
                   REFERENCES auth_user (id) ON DELETE RESTRICT,
    nombre         VARCHAR(120) NOT NULL,
    objetivo       TEXT         NOT NULL,
    fecha_inicio   DATE         NOT NULL DEFAULT CURRENT_DATE,
    fecha_fin      DATE,
    estado         VARCHAR(12)  NOT NULL DEFAULT 'ACTIVO'
                   CHECK (estado IN ('ACTIVO', 'FINALIZADO', 'SUSPENDIDO')),
    observaciones  TEXT         NOT NULL DEFAULT '',
    creado_en      TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    CHECK (fecha_fin IS NULL OR fecha_fin >= fecha_inicio)
);

CREATE TABLE entrenamiento_ejercicio (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    programa_id        BIGINT       NOT NULL
                       REFERENCES entrenamiento_programaentrenamiento (id) ON DELETE CASCADE,
    nombre             VARCHAR(120) NOT NULL,
    series             INTEGER      NOT NULL DEFAULT 3 CHECK (series >= 0),
    repeticiones       VARCHAR(30)  NOT NULL,
    peso_recomendado   NUMERIC(6,2),
    descanso_segundos  INTEGER      NOT NULL DEFAULT 60 CHECK (descanso_segundos >= 0),
    orden              INTEGER      NOT NULL DEFAULT 1 CHECK (orden >= 0),
    observaciones      TEXT         NOT NULL DEFAULT '',
    UNIQUE (programa_id, orden)
);

CREATE TABLE entrenamiento_sesionentrenamiento (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    programa_id       BIGINT      NOT NULL
                      REFERENCES entrenamiento_programaentrenamiento (id) ON DELETE RESTRICT,
    fecha_hora        TIMESTAMPTZ NOT NULL,
    duracion_minutos  INTEGER     NOT NULL DEFAULT 60 CHECK (duracion_minutos > 0),
    estado            VARCHAR(12) NOT NULL DEFAULT 'PROGRAMADA'
                      CHECK (estado IN ('PROGRAMADA', 'COMPLETADA', 'CANCELADA')),
    notas_entrenador  TEXT        NOT NULL DEFAULT ''
);

CREATE TABLE entrenamiento_progresocliente (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id         BIGINT       NOT NULL
                       REFERENCES cuentas_cliente (id) ON DELETE RESTRICT,
    entrenador_id      BIGINT       NOT NULL
                       REFERENCES auth_user (id) ON DELETE RESTRICT,
    fecha              DATE         NOT NULL DEFAULT CURRENT_DATE,
    peso_kg            NUMERIC(5,2),
    porcentaje_grasa   NUMERIC(5,2),
    medida_pecho_cm    NUMERIC(5,2),
    medida_cintura_cm  NUMERIC(5,2),
    peso_levantado     NUMERIC(6,1),
    repeticiones       INTEGER CHECK (repeticiones IS NULL OR repeticiones >= 0),
    observaciones      TEXT         NOT NULL DEFAULT ''
);

-- ---------------------------------------------------------------------
-- 6. PROGRAMACIÓN: horarios de entrenadores, clases grupales y reservas
-- ---------------------------------------------------------------------
CREATE TABLE programacion_horarioentrenador (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entrenador_id  BIGINT   NOT NULL
                   REFERENCES auth_user (id) ON DELETE CASCADE,
    dia_semana     SMALLINT NOT NULL CHECK (dia_semana BETWEEN 0 AND 6),  -- 0 = Lunes ... 6 = Domingo
    hora_inicio    TIME     NOT NULL,
    hora_fin       TIME     NOT NULL,
    CHECK (hora_inicio < hora_fin)
);

CREATE TABLE programacion_clasegrupal (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre            VARCHAR(120) NOT NULL,
    descripcion       TEXT         NOT NULL DEFAULT '',
    entrenador_id     BIGINT       NOT NULL
                      REFERENCES auth_user (id) ON DELETE RESTRICT,
    fecha_hora        TIMESTAMPTZ  NOT NULL,
    duracion_minutos  INTEGER      NOT NULL DEFAULT 60 CHECK (duracion_minutos > 0),
    capacidad_maxima  INTEGER      NOT NULL DEFAULT 15 CHECK (capacidad_maxima > 0),
    estado            VARCHAR(12)  NOT NULL DEFAULT 'PROGRAMADA'
                      CHECK (estado IN ('PROGRAMADA', 'CANCELADA', 'FINALIZADA'))
);

CREATE TABLE programacion_reservaclase (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    clase_id    BIGINT      NOT NULL
                REFERENCES programacion_clasegrupal (id) ON DELETE CASCADE,
    cliente_id  BIGINT      NOT NULL
                REFERENCES cuentas_cliente (id) ON DELETE CASCADE,
    estado      VARCHAR(12) NOT NULL DEFAULT 'CONFIRMADA'
                CHECK (estado IN ('CONFIRMADA', 'CANCELADA', 'ASISTIO', 'FALTO')),
    creada_en   TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (clase_id, cliente_id)
);


-- ---------------------------------------------------------------------
-- 7. ÍNDICES sobre claves foráneas
-- ---------------------------------------------------------------------
CREATE INDEX idx_notificacion_cliente   ON cuentas_notificacion (cliente_id);
CREATE INDEX idx_membresia_cliente      ON membresias_membresia (cliente_id);
CREATE INDEX idx_membresia_plan         ON membresias_membresia (plan_id);
CREATE INDEX idx_membresia_vencimiento  ON membresias_membresia (fecha_vencimiento);
CREATE INDEX idx_factura_cliente        ON facturacion_factura (cliente_id);
CREATE INDEX idx_factura_membresia      ON facturacion_factura (membresia_id);
CREATE INDEX idx_pago_factura           ON facturacion_pago (factura_id);
CREATE INDEX idx_programa_cliente       ON entrenamiento_programaentrenamiento (cliente_id);
CREATE INDEX idx_programa_entrenador    ON entrenamiento_programaentrenamiento (entrenador_id);
CREATE INDEX idx_sesion_programa        ON entrenamiento_sesionentrenamiento (programa_id);
CREATE INDEX idx_progreso_cliente       ON entrenamiento_progresocliente (cliente_id);
CREATE INDEX idx_progreso_entrenador    ON entrenamiento_progresocliente (entrenador_id);
CREATE INDEX idx_horario_entrenador     ON programacion_horarioentrenador (entrenador_id);
CREATE INDEX idx_clase_entrenador       ON programacion_clasegrupal (entrenador_id);
CREATE INDEX idx_clase_fecha            ON programacion_clasegrupal (fecha_hora);
CREATE INDEX idx_reserva_cliente        ON programacion_reservaclase (cliente_id);

-- Nota: hay tablas que Django genera automáticamente al hacer migraciones,
-- por eso no se añadieron en este script.

COMMIT;